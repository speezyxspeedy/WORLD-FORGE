export function createGameObjectFromCatalog(
  assetType: AssetType,
  position: Vec3,
  customName?: string
): GameObject {
  const entry = ASSET_CATALOG.find((a) => a.assetType === assetType) || ASSET_CATALOG[0];
  const id = `obj_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 6)}`;
  const isEmissive = entry.materialPreset === 'emissive';
  const isMetal = entry.materialPreset === 'metal';
  const isGlass = entry.materialPreset === 'glass';

  return {
    id,
    name: customName || entry.name,
    assetType: entry.assetType,
    category: entry.category,
    transform: {
      position: { ...position },
      rotation: { x: 0, y: 0, z: 0 },
      scale: { ...entry.defaultScale },
    },
    material: {
      color: entry.defaultColor,
      roughness: isMetal ? 0.32 : isGlass ? 0.15 : 0.72,
      metalness: isMetal ? 0.78 : 0.08,
      emissive: isEmissive ? entry.defaultColor : '#000000',
      emissiveIntensity: isEmissive ? 0.55 : 0,
      opacity: isGlass ? 0.45 : 1,
      preset: entry.materialPreset,
    },
    physics: {
      collidable: entry.collidable,
      isStatic: true,
      mass: 10,
      friction: 0.6,
      bounce: 0.1,
      isTrigger: entry.isTrigger,
    },
    locked: false,
    visible: true,
    tags: [...entry.tags],
  };
}

